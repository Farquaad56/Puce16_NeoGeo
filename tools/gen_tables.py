#!/usr/bin/env python3
"""Génère les fichiers Rust de données (tables). NE PAS éditer les .rs générés ; relancer ce script.
Usage (racine du projet) : python tools/gen_tables.py"""
import re, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def w(path, s):
    p = os.path.join(ROOT, path); os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, "w", encoding="utf-8", newline="\n").write(s); print("écrit", path, len(s))
HDR = "// GENERATED by tools/gen_tables.py — NE PAS ÉDITER. Source : {src}\n"

# ---------- DAC ----------
rows = [l.split() for l in open(ROOT+"/docs/spec/data/dac_lookup.txt") if l.strip() and not l.startswith("#")]
assert len(rows) == 32
s = HDR.format(src="docs/spec/data/dac_lookup.txt (MAME neogeo_v.cpp create_rgb_lookups)")
s += "/// DAC[v5][colonne] ; colonne 0 normal, 1 dark, 2 shadow, 3 dark+shadow. Valeurs 0..=255.\npub const DAC: [[u8; 4]; 32] = [\n"
for r in rows: s += "    [%s, %s, %s, %s],\n" % tuple(r[1:5])
s += "];\n"
w("crates/ng-lspc/src/dac_table.rs", s)

# ---------- ZOOM X + shrink ----------
zx = [0x0080,0x0880,0x0888,0x2888,0x288a,0x2a8a,0x2aaa,0xaaaa,0xaaea,0xbaea,0xbaeb,0xbbeb,0xbbef,0xfbef,0xfbff,0xffff]
s = HDR.format(src="ref/mame-neogeo/neogeo_spr.cpp l.~265 zoom_x_tables")
s += "/// Table de zoom horizontal : bit 15 = premier pixel de la ligne de tuile. Index = nibble SCB2 bits 11-8.\npub const ZOOM_X: [u16; 16] = [\n    " + ", ".join("0x%04X" % v for v in zx) + ",\n];\n"
w("crates/ng-lspc/src/zoom_table.rs", s)

# ---------- CMC ----------
src = open(ROOT+"/ref/mame-neogeo/prot_cmc.cpp", encoding="utf-8", errors="replace").read()
s = HDR.format(src="ref/mame-neogeo/prot_cmc.cpp (tables)")
n = 0
for m in re.finditer(r"static const uint8_t (\w+)\[(\d+)\]\s*=\s*\{(.*?)\};", src, re.S):
    name, size, body = m.group(1), int(m.group(2)), m.group(3)
    vals = [int(v, 16) for v in re.findall(r"0x[0-9a-fA-F]+", body)]
    assert len(vals) == size, (name, len(vals), size)
    s += "pub const %s: [u8; %d] = [\n" % (name.upper(), size)
    for i in range(0, size, 16):
        s += "    " + ", ".join("0x%02X" % v for v in vals[i:i+16]) + ",\n"
    s += "];\n"; n += 1
assert n == 20, n
w("crates/ng-cart/src/cmc_tables.rs", s)

# ---------- ROM defs ----------
import sys
sys.path.insert(0, os.path.join(ROOT, "tools"))
import catalogue
CATALOGUE = catalogue.catalogue()   # [(nom, clé de protection)]
def ID(n): return ("N_" + n.upper()) if n[0].isdigit() else n.upper()
txt = open(ROOT+"/docs/spec/data/romsets_all.txt", encoding="utf-8", errors="replace").read()
neogeo_src = open(ROOT+"/ref/mame-neogeo/neogeo.cpp", encoding="utf-8", errors="replace").read()
RMAP = {"maincpu":"P","fixed":"S","audiocpu":"M","audiocrypt":"MCrypt","ymsnd:adpcma":"V","ymsnd:adpcmb":"VB","sprites":"C"}
def num(x): return int(x.strip(), 0)
def title_of(name):
    m = re.search(r'^GAMEL?\(\s*\d+,\s*%s,.*?ROT\d+,\s*"[^"]*",\s*"((?:[^"\\]|\\.)*)"' % re.escape(name), neogeo_src, re.M)
    return m.group(1).replace('\\"', "'") if m else name
def parse(name):
    m = re.search(r"ROM_START\(\s*%s\s*\)(.*?)ROM_END" % name, txt, re.S)
    body = m.group(1)
    parts = []; sizes = {}; region = None; last = None; extra = {"m1_reload": None}
    I = re.I
    def add(file, off, size, crc, load, src_off=0):
        parts.append(dict(file=file, region=region, dest=off, size=size, src_off=src_off, crc=crc, load=load))
    for line in body.split("\n"):
        line = line.split("/*")[0].split("//")[0].strip()
        if not line: continue
        mm = re.match(r'ROM_REGION(?:16_BE|16_LE)?\(\s*(0x[0-9a-f]+)\s*,\s*"([^"]+)"', line, I)
        if mm:
            tag = mm.group(2).replace("cslot1:", "")
            region = RMAP.get(tag); last = None
            if region: sizes[region] = num(mm.group(1))
            continue
        mm = re.match(r'ROM_LOAD(16_WORD_SWAP|32_WORD_SWAP|16_BYTE)?\(\s*"([^"]+)"\s*,\s*(0x[0-9a-f]+)\s*,\s*(0x[0-9a-f]+)\s*,\s*CRC\(([0-9a-f]+)\)', line, I)
        if mm:
            if region:
                kind = {None:"Plain","16_WORD_SWAP":"WordSwap","32_WORD_SWAP":"Word32Swap","16_BYTE":"Byte"}[mm.group(1)]
                last = (mm.group(2), kind, mm.group(5), num(mm.group(3)), num(mm.group(4)))
                add(mm.group(2), num(mm.group(3)), num(mm.group(4)), int(mm.group(5),16), kind)
            continue
        mm = re.match(r'ROM_CONTINUE\(\s*(0x[0-9a-f]+)\s*,\s*(0x[0-9a-f]+)\s*\)', line, I)
        if mm:
            if region and last:
                f, kind, crc, doff, dsize = last
                add(f, num(mm.group(1)), num(mm.group(2)), int(crc,16), kind, src_off=dsize)
                last = (f, kind, crc, doff, dsize + num(mm.group(2)))
            continue
        mm = re.match(r'ROM_RELOAD\(\s*(0x[0-9a-f]+)\s*,\s*(0x[0-9a-f]+)\s*\)', line, I)
        if mm:
            if region == "M": extra["m1_reload"] = (num(mm.group(1)), num(mm.group(2)))
            continue
        mm = re.match(r'NEO_SFIX_(64K|128K)\(\s*"([^"]+)"\s*,\s*CRC\(([0-9a-f]+)\)', line, I)
        if mm:
            sz = 0x10000 if mm.group(1)=="64K" else 0x20000
            sizes["S"] = 0x20000; region = "S"; last = None
            add(mm.group(2), 0, sz, int(mm.group(3),16), "Plain"); continue
        mm = re.match(r'NEO_BIOS_AUDIO_(64K|128K|256K|512K)\(\s*"([^"]+)"\s*,\s*CRC\(([0-9a-f]+)\)', line, I)
        if mm:
            sz = {"64K":0x10000,"128K":0x20000,"256K":0x40000,"512K":0x80000}[mm.group(1)]
            sizes["M"] = {"64K":0x20000,"128K":0x30000,"256K":0x50000,"512K":0x90000}[mm.group(1)]; region = "M"; last = None
            add(mm.group(2), 0, sz, int(mm.group(3),16), "Plain")
            extra["m1_reload"] = (0x10000, sz); continue
        mm = re.match(r'NEO_BIOS_AUDIO_ENCRYPTED_(128K|256K|512K)\(\s*"([^"]+)"\s*,\s*CRC\(([0-9a-f]+)\)', line, I)
        if mm:
            sz = {"128K":0x20000,"256K":0x40000,"512K":0x80000}[mm.group(1)]
            sizes["M"] = 0x90000; sizes["MCrypt"] = 0x80000; region = "MCrypt"; last = None
            add(mm.group(2), 0, sz, int(mm.group(3),16), "Plain"); continue
    return parts, sizes, extra

out = HDR.format(src="docs/spec/data/romsets_all.txt (MAME neogeo.cpp, BSD-3)")
out += "use crate::types::*;\n\n"
for g, prot in CATALOGUE:
    parts, sizes, extra = parse(g)
    title = catalogue.TITLES.get(g) or title_of(g)
    out += "pub static %s_PARTS: &[RomPart] = &[\n" % ID(g)
    for p in parts:
        out += '    RomPart { file: "%s", region: Region::%s, dest: 0x%X, size: 0x%X, src_off: 0x%X, crc: 0x%08X, load: Load::%s },\n' % (p["file"], p["region"], p["dest"], p["size"], p["src_off"], p["crc"], p["load"])
    out += "];\n"
    sz = lambda k: sizes.get(k, 0)
    out += "pub static %s: CartDef = CartDef {\n    name: \"%s\", title: \"%s\", parts: %s_PARTS,\n" % (ID(g), g, title.replace('"', "'"), ID(g))
    out += "    sizes: RegionSizes { p: 0x%X, s: 0x%X, m: 0x%X, m_crypt: 0x%X, v: 0x%X, vb: 0x%X, c: 0x%X },\n" % tuple(sz(k) for k in ["P","S","M","MCrypt","V","VB","C"])
    mr = extra["m1_reload"]
    out += "    m1_reload: %s,\n" % ("Some((0x%X, 0x%X))" % mr if mr else "None")
    out += "    prot: PROT_%s,\n};\n\n" % prot
out += "pub static ALL_CARTS: &[&CartDef] = &[%s];\n" % ", ".join("&"+ID(g) for g, _ in CATALOGUE)
w("crates/ng-cart/src/defs.rs", out)

types = HDR.format(src="tools/gen_tables.py") + '''#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Region { P, S, M, MCrypt, V, VB, C }
/// Plain : octets contigus. WordSwap : échanger les 2 octets de chaque mot 16 bits (ROM_LOAD16_WORD_SWAP).
/// Byte : octet i du fichier -> dest + 2*i (ROM_LOAD16_BYTE ; dest pair = octets pairs, dest impair = octets impairs).
/// Word32Swap : mot 16 bits k du fichier (octets échangés) -> dest + 4*k (ROM_LOAD32_WORD_SWAP ; dest 0 ou 2).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Load { Plain, WordSwap, Byte, Word32Swap }
/// Lire `size` octets du fichier `file` à partir de l'offset `src_off` (ROM_CONTINUE : src_off != 0) et les placer en `dest` de `region`.
#[derive(Clone, Copy, Debug)]
pub struct RomPart { pub file: &'static str, pub region: Region, pub dest: u32, pub size: u32, pub src_off: u32, pub crc: u32, pub load: Load }
#[derive(Clone, Copy, Debug)]
pub struct RegionSizes { pub p: u32, pub s: u32, pub m: u32, pub m_crypt: u32, pub v: u32, pub vb: u32, pub c: u32 }
#[derive(Clone, Copy, Debug, PartialEq, Eq)] pub enum PDecrypt { None, Sma3, Pvc5 }
#[derive(Clone, Copy, Debug, PartialEq, Eq)] pub enum Cmc { None, C42, C50 }
#[derive(Clone, Copy, Debug, PartialEq, Eq)] pub enum Pcm2 { None, Decrypt(u8), Swap(u8) }
#[derive(Clone, Copy, Debug, PartialEq, Eq)] pub enum RuntimeProt { None, Msx, Sma3, Pvc }
#[derive(Clone, Copy, Debug, PartialEq, Eq)] pub enum FixBank { Std, Garou, Kof2000 }
#[derive(Clone, Copy, Debug)]
pub struct Protection { pub p_decrypt: PDecrypt, pub cmc: Cmc, pub gfx_key: u8, pub sfix_decrypt: bool, pub m1_decrypt: bool, pub pcm2: Pcm2, pub runtime: RuntimeProt, pub fix_bank: FixBank }
#[derive(Clone, Copy, Debug)]
pub struct CartDef { pub name: &'static str, pub title: &'static str, pub parts: &'static [RomPart], pub sizes: RegionSizes, pub m1_reload: Option<(u32, u32)>, pub prot: Protection }

const N: Protection = Protection { p_decrypt: PDecrypt::None, cmc: Cmc::None, gfx_key: 0, sfix_decrypt: false, m1_decrypt: false, pcm2: Pcm2::None, runtime: RuntimeProt::None, fix_bank: FixBank::Std };
pub const PROT_NONE: Protection = N;
pub const PROT_MSX: Protection = Protection { runtime: RuntimeProt::Msx, ..N };
// MS3 : sma.cpp mslug3 : mslug3_decrypt_68k + cmc42_gfx_decrypt(0xAD) + sfix_decrypt ; sma.h get_fixed_bank_type()=1 (Garou)
pub const PROT_MS3: Protection = Protection { p_decrypt: PDecrypt::Sma3, cmc: Cmc::C42, gfx_key: 0xAD, sfix_decrypt: true, runtime: RuntimeProt::Sma3, fix_bank: FixBank::Garou, ..N };
// MS4 : pcm2.cpp mslug4 : cmc50_m1_decrypt + cmc50_gfx_decrypt(0x31) + sfix_decrypt + pcm2.decrypt(V,8) ; pcm2.h fixed bank type 1
pub const PROT_MS4: Protection = Protection { cmc: Cmc::C50, gfx_key: 0x31, sfix_decrypt: true, m1_decrypt: true, pcm2: Pcm2::Decrypt(8), fix_bank: FixBank::Garou, ..N };
// MS5 : pvc.cpp mslug5 : mslug5_decrypt_68k + pcm2.swap(V,2) + cmc50_m1_decrypt + cmc50_gfx_decrypt(0x19) + sfix_decrypt ; pvc.h fixed bank type 1
pub const PROT_MS5: Protection = Protection { p_decrypt: PDecrypt::Pvc5, cmc: Cmc::C50, gfx_key: 0x19, sfix_decrypt: true, m1_decrypt: true, pcm2: Pcm2::Swap(2), runtime: RuntimeProt::Pvc, fix_bank: FixBank::Garou };
// T1005 : puce CMC42 (cmc.cpp) : cmc42_gfx_decrypt(clé) + sfix_decrypt ; banc fixe Garou (type 1)
pub const PROT_C42_ZUPAPA: Protection = Protection { cmc: Cmc::C42, gfx_key: 0xBD, sfix_decrypt: true, fix_bank: FixBank::Garou, ..N };
pub const PROT_C42_GANRYU: Protection = Protection { cmc: Cmc::C42, gfx_key: 0x07, sfix_decrypt: true, fix_bank: FixBank::Garou, ..N };
pub const PROT_C42_S1945P: Protection = Protection { cmc: Cmc::C42, gfx_key: 0x05, sfix_decrypt: true, fix_bank: FixBank::Garou, ..N };
pub const PROT_C42_PREISLE2: Protection = Protection { cmc: Cmc::C42, gfx_key: 0x9F, sfix_decrypt: true, fix_bank: FixBank::Garou, ..N };
pub const PROT_C42_BANGBEAD: Protection = Protection { cmc: Cmc::C42, gfx_key: 0xF8, sfix_decrypt: true, fix_bank: FixBank::Garou, ..N };
pub const PROT_C42_NITD: Protection = Protection { cmc: Cmc::C42, gfx_key: 0xFF, sfix_decrypt: true, fix_bank: FixBank::Garou, ..N };
pub const PROT_C42_SENGOKU3: Protection = Protection { cmc: Cmc::C42, gfx_key: 0xFE, sfix_decrypt: true, fix_bank: FixBank::Garou, ..N };
'''
w("crates/ng-cart/src/types.rs", types)
